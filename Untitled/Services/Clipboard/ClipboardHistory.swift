import AppKit
import CryptoKit
import ImageIO
import Observation
import OSLog
import UniformTypeIdentifiers

/// One thing you copied: text, or an image kept as a PNG file.
nonisolated struct ClipboardEntry: Identifiable, Codable, Equatable, Sendable {
    enum Content: Codable, Equatable, Sendable {
        case text(String)
        /// `file` is the PNG's name inside the history folder.
        case image(file: String, width: Int, height: Int)
    }

    let id: UUID
    var date: Date
    var content: Content
    /// The app that was in front when it was copied.
    var appName: String?
    /// Identifies identical copies, so copying the same thing again moves it to the top.
    var fingerprint: String

    var text: String? {
        if case .text(let text) = content { text } else { nil }
    }

    var isImage: Bool {
        if case .image = content { true } else { false }
    }
}

/// Invalidates image work that started before Clear or a pause/resume change.
nonisolated struct ClipboardHistoryGeneration: Sendable {
    private(set) var value = 0

    mutating func invalidate() {
        value &+= 1
    }

    func accepts(_ token: Int, isEnabled: Bool) -> Bool {
        isEnabled && token == value
    }
}

/// Limits both edge length and the total decoded pixel count for clipboard images.
nonisolated enum ClipboardImageBounds {
    static let maximumPixels = 40_000_000
    static let maximumDimension = 16_384

    static func permits(width: Int, height: Int) -> Bool {
        width > 0 && height > 0
            && width <= maximumDimension && height <= maximumDimension
            && width <= maximumPixels / height
    }
}

/// Everything you copy in any app, newest first, kept until you remove it or the limit in
/// Settings › Clipboard says otherwise.
///
/// macOS has no notification for clipboard changes, so the clipboard's change count is checked
/// twice a second, which costs next to nothing. The contents are read only when it changes.
/// Copies that apps mark as private or temporary (password managers do), copies made while
/// an excluded app is in front, and retrace's own copies are never kept. Everything stays
/// on this Mac, in Application Support.
@Observable
final class ClipboardHistory {
    private(set) var entries: [ClipboardEntry] = []

    @ObservationIgnored private let settings: SettingsStore
    @ObservationIgnored private let clipboard: any ClipboardWriting
    @ObservationIgnored private let folder: URL?
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var historyGeneration = ClipboardHistoryGeneration()
    @ObservationIgnored private let log = Logger(subsystem: Log.subsystem, category: "clipboard")

    /// The longest text kept, so a huge copy doesn't bloat the history.
    nonisolated private static let maximumTextLength = 500_000
    /// Largest compressed clipboard payload kept; decoded pixels use `ClipboardImageBounds`.
    nonisolated private static let maximumImageBytes = 60 * 1_048_576

    /// Types apps use to say "don't keep this" (see nspasteboard.org).
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
    ]

    private static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png, .tiff, NSPasteboard.PasteboardType(UTType.jpeg.identifier), NSPasteboard.PasteboardType(UTType.heic.identifier),
    ]

    init(settings: SettingsStore, clipboard: any ClipboardWriting, folder: URL? = ClipboardHistory.defaultFolder) {
        self.settings = settings
        self.clipboard = clipboard
        self.folder = folder
        load()
        followRetention()
    }

    /// Application Support/<bundle ID>/Clipboard, so a development build keeps its own.
    static var defaultFolder: URL? {
        guard let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first else { return nil }
        return support.appending(path: Bundle.main.bundleIdentifier ?? "Untitled", directoryHint: .isDirectory)
            .appending(path: "Clipboard", directoryHint: .isDirectory)
    }

    private var indexURL: URL? { folder?.appending(path: "History.json") }

    func imageURL(for entry: ClipboardEntry) -> URL? {
        guard case .image(let file, _, _) = entry.content else { return nil }
        return folder?.appending(path: file)
    }

    // MARK: Watching

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        followClipboardHistorySetting()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard settings.keepsClipboardHistory, count != clipboard.lastWriteChangeCount else { return }

        let types = Set(pasteboard.types ?? [])
        guard !types.isEmpty, types.isDisjoint(with: Self.privateTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication
        if let id = app?.bundleIdentifier, settings.clipboardExcludedApps.contains(id) { return }
        let appName = app?.localizedName
        let generation = historyGeneration.value

        // A copied file: keep it only when it's an image, as the image itself.
        if types.contains(.fileURL) {
            let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
            guard let url = urls.first(where: { UTType(filenameExtension: $0.pathExtension)?.conforms(to: .image) == true }) else { return }
            Task { await addImage(fromFileAt: url, appName: appName, generation: generation) }
            return
        }
        if let type = Self.imageTypes.first(where: types.contains), let data = pasteboard.data(forType: type) {
            guard data.count <= Self.maximumImageBytes else { return }
            Task { await addImage(data, appName: appName, generation: generation) }
            return
        }
        if let text = pasteboard.string(forType: .string) {
            addText(text, appName: appName)
        }
    }

    // MARK: Adding

    private func addText(_ text: String, appName: String?) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= Self.maximumTextLength else { return }
        let fingerprint = "text:" + Self.digest(Data(text.utf8))
        insert(ClipboardEntry(id: UUID(), date: .now, content: .text(text), appName: appName, fingerprint: fingerprint))
    }

    private func addImage(fromFileAt url: URL, appName: String?, generation: Int) async {
        let data = await Task.detached(priority: .utility) { () -> Data? in
            guard let size = (try? url.resourceValues(forKeys: [.fileSizeKey]))?.fileSize, size <= Self.maximumImageBytes else { return nil }
            return try? Data(contentsOf: url)
        }.value
        guard let data, canKeepImage(generation: generation) else { return }
        await addImage(data, appName: appName, generation: generation)
    }

    /// Hashes and converts to PNG off the main thread, then keeps it unless already present.
    private func addImage(_ data: Data, appName: String?, generation: Int) async {
        guard let folder, canKeepImage(generation: generation) else { return }
        let digest = await Task.detached(priority: .utility) {
            Self.digest(data)
        }.value
        guard canKeepImage(generation: generation) else { return }
        let fingerprint = "image:" + digest
        if let index = entries.firstIndex(where: { $0.fingerprint == fingerprint }) {
            var entry = entries.remove(at: index)
            entry.date = .now
            entries.insert(entry, at: 0)
            save()
            return
        }
        let name = UUID().uuidString + ".png"
        let destination = folder.appending(path: name)
        let size = await Task.detached(priority: .utility) { () -> CGSize? in
            try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            return Self.writePNG(from: data, to: destination)
        }.value
        guard let size else {
            log.error("A copied image couldn't be read")
            return
        }
        guard canKeepImage(generation: generation) else {
            try? FileManager.default.removeItem(at: destination)
            return
        }
        insert(ClipboardEntry(
            id: UUID(),
            date: .now,
            content: .image(file: name, width: Int(size.width), height: Int(size.height)),
            appName: appName,
            fingerprint: fingerprint
        ))
    }

    private func insert(_ entry: ClipboardEntry) {
        if let index = entries.firstIndex(where: { $0.fingerprint == entry.fingerprint }) {
            let old = entries.remove(at: index)
            if old.content != entry.content { deleteFiles(of: [old]) }
        }
        entries.insert(entry, at: 0)
        applyRetention()
        save()
    }

    // MARK: Using

    /// Puts an entry back on the clipboard. It stays where it is in the list, so a double-click
    /// still lands on the same item.
    func copy(_ entry: ClipboardEntry) {
        switch entry.content {
        case .text(let text):
            clipboard.copy(text: text)
        case .image:
            guard let url = imageURL(for: entry), let image = NSImage(contentsOf: url) else { return }
            clipboard.copy(image)
        }
    }

    func remove(_ ids: Set<ClipboardEntry.ID>) {
        let removed = entries.filter { ids.contains($0.id) }
        guard !removed.isEmpty else { return }
        entries.removeAll { ids.contains($0.id) }
        deleteFiles(of: removed)
        save()
    }

    func removeAll() {
        historyGeneration.invalidate()
        deleteFiles(of: entries)
        entries = []
        save()
    }

    private func canKeepImage(generation: Int) -> Bool {
        historyGeneration.accepts(generation, isEnabled: settings.keepsClipboardHistory)
    }

    /// Invalidates in-flight image conversions when history is paused, including if it is
    /// quickly re-enabled before a conversion finishes.
    private func followClipboardHistorySetting() {
        withObservationTracking {
            _ = settings.keepsClipboardHistory
        } onChange: { [weak self] in
            Task { @MainActor [weak self] in
                guard let self else { return }
                historyGeneration.invalidate()
                followClipboardHistorySetting()
            }
        }
    }

    // MARK: Retention

    /// A shorter limit in Settings applies right away.
    private func followRetention() {
        withObservationTracking {
            _ = settings.clipboardRetention
        } onChange: { [weak self] in
            Task { @MainActor [weak self] in
                guard let self else { return }
                if applyRetention() { save() }
                followRetention()
            }
        }
    }

    /// Removes what the limit in Settings no longer keeps. Returns whether anything went.
    @discardableResult
    private func applyRetention() -> Bool {
        let retention = settings.clipboardRetention
        var removed: [ClipboardEntry] = []
        if let age = retention.maximumAge {
            let cutoff = Date.now.addingTimeInterval(-age)
            removed += entries.filter { $0.date < cutoff }
            entries.removeAll { $0.date < cutoff }
        }
        if let count = retention.maximumCount, entries.count > count {
            removed += entries[count...]
            entries.removeLast(entries.count - count)
        }
        deleteFiles(of: removed)
        return !removed.isEmpty
    }

    // MARK: Storage

    private func deleteFiles(of removed: [ClipboardEntry]) {
        for entry in removed {
            if let url = imageURL(for: entry) { try? FileManager.default.removeItem(at: url) }
        }
    }

    private func load() {
        guard let indexURL, let data = try? Data(contentsOf: indexURL) else { return }
        do {
            entries = try JSONDecoder().decode([ClipboardEntry].self, from: data).sorted { $0.date > $1.date }
            if applyRetention() { save() }
        } catch {
            log.error("Clipboard history was unreadable: \(error.localizedDescription, privacy: .public)")
        }
    }

    private func save() {
        guard let indexURL, let folder else { return }
        do {
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            try JSONEncoder().encode(entries).write(to: indexURL, options: .atomic)
        } catch {
            log.error("Saving clipboard history failed: \(error.localizedDescription, privacy: .public)")
        }
    }

    nonisolated private static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).prefix(16).map { String(format: "%02x", $0) }.joined()
    }

    /// Writes any image data as a PNG and returns its pixel size.
    nonisolated private static func writePNG(from data: Data, to url: URL) -> CGSize? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = (properties[kCGImagePropertyPixelWidth] as? NSNumber)?.intValue,
              let height = (properties[kCGImagePropertyPixelHeight] as? NSNumber)?.intValue,
              width > 0,
              height > 0,
              ClipboardImageBounds.permits(width: width, height: height),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil),
              let destination = CGImageDestinationCreateWithURL(url as CFURL, UTType.png.identifier as CFString, 1, nil)
        else { return nil }

        var finalized = false
        defer {
            if !finalized { try? FileManager.default.removeItem(at: url) }
        }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination) else { return nil }
        finalized = true
        return CGSize(width: image.width, height: image.height)
    }
}
